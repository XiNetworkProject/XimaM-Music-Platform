import puppeteer from 'puppeteer';
import dotenv from 'dotenv';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
dotenv.config({ path: '.env.local', quiet: true });
const base = 'http://localhost:3000';
const browser = await puppeteer.launch({ headless: true });
const page = await browser.newPage();
page.setDefaultTimeout(40000);
page.setDefaultNavigationTimeout(90000);
const result = { status: 'RUNNING', checks: [], errors: [] };
const ready = async s => { const handle = await page.waitForSelector(s); await handle?.dispose(); };
page.on('pageerror', e => result.errors.push(e.message));
try {
  await page.goto(base + '/auth/signin'); await ready('input[type="email"]');
  await page.type('input[type="email"]', process.env.SYNAURA_E2E_EMAIL);
  await page.type('input[type="password"]', process.env.SYNAURA_E2E_PASSWORD);
  await page.click('button[type="submit"]');
  await page.waitForFunction(() => !location.pathname.startsWith('/auth/signin'));
  const postId = await page.evaluate(async () => { const b = await (await fetch('/api/posts?limit=5')).json(); return b.posts?.[0]?.id; });
  assert(postId, 'No real public post available'); result.postId = postId;
  await page.goto(base + '/posts/' + postId, { waitUntil: 'networkidle2' });
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent.includes('Commentaires')));
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.includes('Commentaires')).click());
  await ready('[data-comments-state="loaded"]');
  assert.equal(await page.$eval('[data-comments-entity]', e => e.dataset.commentsEntity), 'post:' + postId);
  assert.equal(await page.$('#comments-tab-moments'), null);
  result.checks.push('Post canonical entity; no invented timestamp or waveform');
  await page.type('textarea', 'Brouillon de test non envoyé');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('[data-comments-entity]'));
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.includes('Commentaires')).click());
  await ready('[data-comments-state="loaded"]');
  assert.equal(await page.$eval('textarea', e => e.value), 'Brouillon de test non envoyé');
  result.checks.push('Post draft preserved across close/reopen');
  await page.setViewport({ width: 390, height: 844 });
  await page.screenshot({ path: 'docs/comments-moments-phase4b4-captures/mobile-post-390.png' });
  await page.goBack(); await page.waitForFunction(() => !document.querySelector('[data-comments-entity]'));
  assert.equal(new URL(page.url()).pathname, '/posts/' + postId);
  result.checks.push('Back closes Post comments without leaving canonical route');
  await page.setViewport({ width: 1440, height: 900 });
  await page.goto(base + '/dev/live', { waitUntil: 'networkidle2' });
  await ready('[data-active="true"] button[aria-label^="Commentaires de "]');
  await page.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Ouvrir le Flow')?.click());
  await page.click('[data-active="true"] button[aria-label^="Commentaires de "]');
  await ready('[data-comments-state="loaded"]');
  await page.evaluate(() => document.querySelectorAll('[role="status"] button[aria-label="Fermer"]').forEach(b => b.click()));
  await new Promise(r => setTimeout(r, 500));
  await page.screenshot({ path: 'docs/comments-moments-phase4b4-captures/desktop-conversation-1440.png' });
  await page.click('#comments-tab-moments');
  await page.screenshot({ path: 'docs/comments-moments-phase4b4-captures/desktop-moments-1440.png' });
  result.status = 'PASS';
} catch(e) { result.status = 'FAIL'; result.error = String(e.stack || e); process.exitCode = 1; }
finally { await fs.writeFile('docs/comments-moments-phase4b4-captures/post-results.json', JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2)); await browser.close(); }
